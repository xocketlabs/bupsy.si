import Foundation

/// Writes the hook script and settings file that make an engine ask before it acts.
public enum GateInstaller {
    /// How long Claude Code is told to wait for the hook.
    public static let hookTimeoutSeconds = 900

    /// How long the script waits before deciding for itself.
    ///
    /// **Deliberately shorter than the hook timeout, and this is the whole safety argument.**
    /// A `PreToolUse` hook that times out does *not* block — the call proceeds through the normal
    /// permission flow. So a gate that simply waited would fail *open* precisely when nobody was
    /// watching, which is the worst possible moment. Instead the script answers `deny` with time
    /// to spare, and the harness never reaches its own timeout.
    public static let scriptTimeoutSeconds = 870

    /// Produces a directory containing `settings.json` and `gate.sh`, and returns the settings
    /// path to pass to `claude --settings`.
    public static func install(gateDirectory: URL, timeoutSeconds: Int = scriptTimeoutSeconds)
        throws -> URL
    {
        // Refused rather than clamped. A gate that quietly becomes fail-open is worse than one
        // that will not install, and a caller passing this has misunderstood the mechanism.
        guard timeoutSeconds < hookTimeoutSeconds else {
            throw GateError.timeoutWouldFailOpen(
                script: timeoutSeconds, hook: hookTimeoutSeconds)
        }

        let script = gateDirectory.appendingPathComponent("gate.sh")
        let settings = gateDirectory.appendingPathComponent("settings.json")

        try Data(shellScript(gateDirectory: gateDirectory, timeoutSeconds: timeoutSeconds).utf8)
            .write(to: script, options: .atomic)
        try FileManager.default.setAttributes(
            [.posixPermissions: 0o755], ofItemAtPath: script.path)

        try Data(settingsJSON(scriptPath: script.path).utf8).write(to: settings, options: .atomic)
        return settings
    }

    static func settingsJSON(scriptPath: String) -> String {
        // Matches every tool. Narrowing happens in AutonomyPolicy, not here, so that one place
        // decides what needs a human and the audit log sees every call either way.
        let payload: [String: Any] = [
            "hooks": [
                "PreToolUse": [[
                    "matcher": "*",
                    "hooks": [[
                        "type": "command",
                        "command": scriptPath,
                        "timeout": hookTimeoutSeconds,
                        "statusMessage": "waiting for your approval in bupsy",
                    ]],
                ]]
            ]
        ]
        return (try? String(
            data: JSONSerialization.data(withJSONObject: payload, options: [.prettyPrinted, .sortedKeys]),
            encoding: .utf8)) ?? "{}"
    }

    /// The hook body. Plain `sh` and coreutils only — it has to run unchanged on this Mac and
    /// inside a rented Linux machine, and anything it depends on is something that can be missing
    /// at 3am. The gate directory is baked in at generation time rather than read from the
    /// environment, because a hook's environment is not ours to rely on.
    static func shellScript(gateDirectory: URL, timeoutSeconds: Int = scriptTimeoutSeconds) -> String {
        """
        #!/bin/sh
        # Generated by bupsy. Holds a tool call open until a human decides.
        #
        # Fails CLOSED: if nobody answers in time this denies, because a hook that lets its own
        # timeout lapse causes the tool call to proceed.
        set -u

        GATE='\(gateDirectory.path)'
        ID="$$-$(date +%s)-$(awk 'BEGIN{srand();printf "%d", rand()*100000}')"
        PENDING="$GATE/pending/$ID.json"
        DECISION="$GATE/decisions/$ID.json"

        mkdir -p "$GATE/pending" "$GATE/decisions" "$GATE/expired"

        # Write atomically: the watcher polls this directory and must never read half a file.
        cat > "$PENDING.part" && mv "$PENDING.part" "$PENDING"

        i=0
        while [ "$i" -lt \(timeoutSeconds) ]; do
            if [ -f "$DECISION" ]; then
                cat "$DECISION"
                rm -f "$DECISION" "$PENDING"
                exit 0
            fi
            sleep 1
            i=$((i + 1))
        done

        rm -f "$PENDING"
        # Tells the app this one was denied for lack of an answer, so its card can settle.
        mkdir -p "$GATE/expired"
        : > "$GATE/expired/$ID"
        printf '%s\\n' '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"bupsy: nobody approved this in time, so it was denied"}}'
        exit 0
        """
    }
}

public enum GateError: Error, Equatable, LocalizedError {
    /// The script would wait as long as, or longer than, the harness — which converts a
    /// fail-closed gate into a fail-open one. See `GateInstaller.scriptTimeoutSeconds`.
    case timeoutWouldFailOpen(script: Int, hook: Int)

    public var errorDescription: String? {
        switch self {
        case .timeoutWouldFailOpen(let script, let hook):
            "A gate waiting \(script)s cannot sit inside a \(hook)s hook timeout: the tool call "
                + "would proceed unapproved. Keep the script's wait below the hook's."
        }
    }
}
